#!/usr/bin/env python3
"""The Brandhoop palette, in one place. Everything else is generated from it:

    site/assets/brand-tokens.css      CSS variables for the website and the pages under it
    lib/app/palette.dart              the same colours as Dart constants for the Flutter app
    site/brand/palette/index.html     a swatch page with the contrast checks

    python3 tools/brand/palette.py

Ramps keep the three colours of the logo (deep navy, burnt orange, slate) and fill in
lighter and darker steps. Every text-on-background pair that the pages use is checked
for WCAG contrast and the script stops if one falls below its target.
"""
import html, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]

RAMPS = {
    # name: {step: hex}. 700 / 500 / 600 are the logo colours.
    'navy': {50: '#EEF0F7', 100: '#DDE1EF', 200: '#B9C0DC', 300: '#8F99C0', 400: '#5F6B9B', 500: '#3C4775', 600: '#2B3558', 700: '#1F2744', 800: '#141A33', 900: '#0B0F20'},
    'saffron': {50: '#FFF4EC', 100: '#FBE3D2', 200: '#F6C6A3', 300: '#F1A774', 400: '#F08A45', 500: '#D8662A', 600: '#B9501A', 700: '#A9481C', 800: '#7A3B00', 900: '#4A2208'},
    'slate': {50: '#F6F6F8', 100: '#ECEEF2', 200: '#E1E4EA', 300: '#C5CAD4', 400: '#A4ABBD', 500: '#7F8798', 600: '#566170', 700: '#3F4859', 800: '#272D3D', 900: '#14182B'},
}
STATUS = {'green': '#2E7D32', 'green-soft': '#E3F1E4', 'red': '#C62828', 'red-soft': '#FBE4E4', 'amber': '#B26A00', 'amber-soft': '#FFF0D6'}
NAMES = {'navy': 'Navy', 'saffron': 'Saffron', 'slate': 'Slate'}
USE = {
    'navy': 'Brand, headings, dark hero and bars. 700 is the logo navy.',
    'saffron': 'The single accent: buttons, highlights, active states. 500 is the logo orange.',
    'slate': 'Text, borders and page grounds. Cool, so it sits well beside the navy.',
}

# semantic tokens: name -> (light, dark), each a ramp reference or a hex
SEMANTIC = {
    'bg':        ('slate-50',  '#0F1322'),
    'surface':   ('#FFFFFF',   '#181D33'),
    'surface-2': ('slate-100', '#222845'),
    'line':      ('slate-200', '#2A3050'),
    'ink':       ('slate-900', '#ECEEF6'),
    'muted':     ('slate-600', '#A4ABBD'),
    'brand':     ('navy-700',  '#C9D0EE'),
    'brand-deep': ('navy-800', '#141A33'),
    'accent':    ('saffron-500', 'saffron-400'),
    'accent-ink': ('slate-900', 'slate-900'),      # text on an accent button
    'accent-soft': ('saffron-100', '#3A2A24'),
    'accent-text': ('saffron-700', 'saffron-300'), # accent used as small text
    'ok':        ('#2E7D32',   '#7BC47F'),
    'bad':       ('#C62828',   '#F28B82'),
}
HERO = ('#2B3558', '#1F2744', '#141A33')   # the dark hero gradient, same in both themes


def ref(v):
    if v.startswith('#'): return v.upper()
    n, s = v.rsplit('-', 1); return RAMPS[n][int(s)]


def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def contrast(a, b):
    la, lb = sorted((lum(ref(a)), lum(ref(b))), reverse=True); return (la + 0.05) / (lb + 0.05)


# (foreground, background, minimum ratio, what it is) for light and dark
CHECKS = [
    ('ink', 'bg', 7, 'Body text on the page'), ('ink', 'surface', 7, 'Body text on a card'), ('muted', 'bg', 4.5, 'Secondary text on the page'),
    ('muted', 'surface', 4.5, 'Secondary text on a card'), ('brand', 'surface', 4.5, 'Brand-coloured text on a card'),
    ('accent-ink', 'accent', 4.5, 'Label on an accent button'), ('accent-text', 'surface', 4.5, 'Accent used as small text on a card'),
    ('accent-text', 'accent-soft', 4.5, 'Accent text on its soft tint'), ('ink', 'accent-soft', 4.5, 'Text on the soft accent tint'),
]
HERO_CHECKS = [('#FFFFFF', HERO[1], 7, 'White text on the hero'), ('#F6C6A3', HERO[1], 4.5, 'Soft orange text on the hero'), ('#D8662A', HERO[1], 3, 'Accent button on the hero (large text)')]


def check():
    rows = []
    for i, mode in enumerate(('light', 'dark')):
        for f, b, mn, what in CHECKS:
            F, B = SEMANTIC[f][i], SEMANTIC[b][i]
            r = contrast(F, B); rows.append((mode, what, ref(F), ref(B), r, mn))
    for f, b, mn, what in HERO_CHECKS:
        r = contrast(f, b); rows.append(('hero', what, ref(f), ref(b), r, mn))
    bad = [x for x in rows if x[4] < x[5]]
    for x in bad: print('LOW CONTRAST', x)
    if bad: raise SystemExit(1)
    return rows


def css():
    L = []
    for n, r in RAMPS.items():
        for s, h in r.items(): L.append(f'  --{n}-{s}: {h};')
    for n, h in STATUS.items(): L.append(f'  --{n}: {h};')
    L.append(f'  --hero-1: {HERO[0]}; --hero-2: {HERO[1]}; --hero-3: {HERO[2]};')
    light = '\n'.join(f'  --{k}: {ref(v[0])};' for k, v in SEMANTIC.items())
    dark = '\n'.join(f'  --{k}: {ref(v[1])};' for k, v in SEMANTIC.items())
    return ('/* Generated by tools/brand/palette.py: edit the palette there, not here. */\n:root {\n' + '\n'.join(L) + '\n' + light + '\n  color-scheme: light;\n}\n'
            '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n' + dark.replace('\n  ', '\n    ').replace('  --bg', '    --bg', 1) + '\n    color-scheme: dark;\n  }\n}\n'
            ':root[data-theme="dark"] {\n' + dark + '\n  color-scheme: dark;\n}\n')


def dart():
    L = ["// Generated by tools/brand/palette.py: edit the palette there, not here.\nimport 'package:flutter/painting.dart';\n\n/// The Brandhoop palette: ramps (50 lightest, 900 darkest) and the semantic colours of both themes.\nclass Palette {\n  const Palette._();\n"]
    for n, r in RAMPS.items():
        for s, h in r.items(): L.append(f"  static const Color {n}{s} = Color(0xFF{h[1:]});")
        L.append('')
    for n, h in STATUS.items():
        camel = ''.join(w.capitalize() if i else w for i, w in enumerate(n.split('-')))
        L.append(f"  static const Color {camel} = Color(0xFF{h[1:]});")
    L.append('')
    L.append('  /// The hero gradient, light to dark; the same in both themes.')
    L.append('  static const List<Color> hero = <Color>[' + ', '.join(f'Color(0xFF{h[1:]})' for h in HERO) + '];')
    L.append('')
    for mode, i in (('light', 0), ('night', 1)):
        for k, v in SEMANTIC.items():
            camel = ''.join(w.capitalize() if j else w for j, w in enumerate(k.split('-')))
            L.append(f"  static const Color {mode}{camel[0].upper()}{camel[1:]} = Color(0xFF{ref(v[i])[1:]});")
        L.append('')
    L.append('}\n')
    return '\n'.join(L)


